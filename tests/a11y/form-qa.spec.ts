import { expect, test } from '@playwright/test'

test('Form QA is reachable from the documentation sidebar', async ({ page }) => {
    await page.goto('/components/divider/')
    await page.getByRole('link', { name: 'Form QA' }).click()
    await expect(page).toHaveURL(/\/form-qa\.html$/)
    await expect(page.getByRole('heading', { name: 'Form QA', level: 1 })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Form QA' })).toHaveAttribute('aria-current', 'page')
})

test('logs submitter, ordered data, validation and button actions', async ({ page }) => {
    await page.goto('/form-qa.html')
    const events = page.getByRole('list', { name: 'Form events' })
    const submits = events.getByText('submit · qa-primary', { exact: true })
    await page.getByRole('button', { name: 'MDC button', exact: true }).click()
    await page.getByRole('button', { name: 'Icon button', exact: true }).click()
    await page.getByRole('button', { name: 'Native button', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Disabled submit' })).toBeDisabled()
    await expect(events.getByRole('listitem')).toHaveCount(0)

    await page.getByRole('button', { name: 'MDC submit', exact: true }).click()
    await expect(submits).toHaveCount(1)
    const latest = events.getByRole('listitem').first()
    await expect(latest).toContainText('submitter = mdc-button#qa-button-submit')
    await expect(latest).toContainText('"action" = "button-submit"')
    await expect(latest.locator('pre')).toContainText(/"price" = "20"\s+"price" = "80"/)
    await page.getByRole('button', { name: 'Icon submit', exact: true }).click()
    await expect(submits).toHaveCount(2)
    await expect(latest).toContainText('submitter = mdc-icon-button#qa-icon-submit')
    await expect(latest).toContainText('"action" = "icon-submit"')
    await page.getByRole('button', { name: 'Native submit', exact: true }).click()
    await expect(submits).toHaveCount(3)
    await expect(latest).toContainText('submitter = button#qa-native-submit')
    await expect(latest).toContainText('"action" = "native-submit"')

    const email = page.getByRole('textbox', { name: 'Email' })
    await email.fill('')
    await page.getByRole('button', { name: 'External submit A' }).click()
    await expect(events.getByText('invalid · qa-email', { exact: true }).first()).toBeVisible()
    await expect(submits).toHaveCount(3)
    await email.fill('new@example.test')
    await page.getByRole('button', { name: 'External submit A' }).click()
    await expect(submits).toHaveCount(4)
    await expect(latest).toContainText('submitter = mdc-button#qa-external-submit')
    await expect(latest).toContainText('"email" = "new@example.test"')

    await page.getByRole('button', { name: 'Request submit B' }).click()
    await expect(latest).toContainText('submit · qa-secondary')
    await expect(latest).toContainText('submitter = (none)')
    await expect(latest).toContainText('"second" = "yes"')
})

test('reset defaults take effect only on reset and restore reloads the fixture', async ({ page }) => {
    await page.goto('/form-qa.html')
    const current = page.getByRole('checkbox', { name: 'mdc-checkbox · Current only', exact: true })
    const resetDefault = page.getByRole('checkbox', { name: 'mdc-checkbox · Reset default only', exact: true })
    const currentSwitch = page.getByRole('switch', { name: 'mdc-switch · Current only', exact: true })
    const defaultSwitch = page.getByRole('switch', { name: 'mdc-switch · Reset default only', exact: true })
    const events = page.getByRole('list', { name: 'Form events' })
    await expect(current).toBeChecked()
    await expect(resetDefault).not.toBeChecked()
    await expect(currentSwitch).toBeChecked()
    await expect(defaultSwitch).not.toBeChecked()
    await page.getByRole('button', { name: 'MDC reset', exact: true }).click()
    await expect(current).not.toBeChecked()
    await expect(resetDefault).toBeChecked()
    await expect(currentSwitch).not.toBeChecked()
    await expect(defaultSwitch).toBeChecked()
    await expect(events.getByRole('listitem').first()).toContainText('"checkbox-default" = "on"')

    const inspector = page.getByRole('region', { name: 'Inspector' })
    const editor = inspector.getByRole('group', { name: 'Example attributes' })
    await inspector.getByLabel('Example', { exact: true }).selectOption('checkbox-default')
    await editor.getByLabel('default-checked', { exact: true }).uncheck()
    await expect(resetDefault).toBeChecked()
    await page.getByRole('button', { name: 'External reset A' }).click()
    await expect(resetDefault).not.toBeChecked()
    await inspector.getByRole('button', { name: 'Restore example' }).click()
    await expect(editor.getByLabel('default-checked', { exact: true })).toBeChecked()
    await expect(resetDefault).not.toBeChecked()
    await page.getByRole('button', { name: 'Native reset', exact: true }).click()
    await expect(resetDefault).toBeChecked()
    await page.getByRole('button', { name: 'Reset A via API' }).click()
    await expect(events.getByRole('listitem').first()).toContainText('reset · qa-primary')
})

test('reassigns a control between forms and tracks label activation', async ({ page }) => {
    await page.goto('/form-qa.html')
    const inspector = page.getByRole('region', { name: 'Inspector' })
    await inspector.getByLabel('Example', { exact: true }).selectOption('external-check')
    const state = page.locator('#qa-state')
    const dataA = page.locator('#qa-primary-data')
    const dataB = page.locator('#qa-secondary-data')
    await expect(state).toContainText('owner = qa-primary')
    await page.getByText('External checkbox label', { exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'External checkbox label' })).toBeFocused()
    await expect(state).toContainText('focused = qa-external-check')
    await expect(dataA).toContainText('"external" = "yes"')

    const form = inspector.getByLabel('form', { exact: true })
    await form.selectOption('qa-secondary')
    await expect(state).toContainText('owner = qa-secondary')
    await expect(dataA).not.toContainText('"external"')
    await expect(dataB).toContainText('"external" = "yes"')
    await form.selectOption('qa-missing')
    await expect(state).toContainText('owner = (none)')
    await expect(dataB).not.toContainText('"external"')
    await form.selectOption('')
    await expect(state).toContainText('owner = (none)')
    await inspector.getByRole('button', { name: 'Restore example' }).click()
    await expect(state).toContainText('owner = qa-primary')
    await expect(dataA).not.toContainText('"external"')
})

test('edits the button type and exercises same-name choices and picker values', async ({ page }) => {
    const errors: Error[] = []
    page.on('pageerror', error => errors.push(error))
    await page.goto('/form-qa.html')
    const inspector = page.getByRole('region', { name: 'Inspector' })
    const example = inspector.getByLabel('Example', { exact: true })
    const events = page.getByRole('list', { name: 'Form events' })
    const dataA = page.locator('#qa-primary-data')
    await expect(dataA).toContainText('"fruit" = "apple"')
    await expect(dataA).toContainText('"legacy" = "25"')
    await expect(dataA).toContainText('"date" = "2026-01-12"')
    await expect(dataA).toContainText('"time" = "09:30"')
    const open = page.getByRole('button', { name: 'Open Time picker', exact: true })
    await open.click()
    await expect(page.locator('mdc-time-picker dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.locator('mdc-time-picker dialog')).toBeHidden()

    const radioA = page.locator('#qa-mdc-radio-button-group-a')
    const radioB = page.locator('#qa-mdc-radio-button-group-b')
    await expect(radioA).toHaveJSProperty('checked', true)
    await radioB.click()
    await expect(radioB).toHaveJSProperty('checked', true)
    await expect(radioA).toHaveJSProperty('checked', false)

    await example.selectOption('button-button')
    await inspector.getByLabel('type', { exact: true }).selectOption('reset')
    await page.getByRole('button', { name: 'MDC button', exact: true }).click()
    await expect(events.getByRole('listitem').first()).toContainText('reset · qa-primary')
    await expect(dataA).toContainText('"rating" = "60"')
    await expect(dataA).not.toContainText('"date"')
    await expect(dataA).toContainText('"time" = "12:00"')
    await expect(radioB).toHaveJSProperty('checked', true)
    expect(errors).toEqual([])
})
